void LCD_Text(int x, int y, const char* str, uint16_t fg, uint16_t bg, int size) {
    while (*str) {
        const uint8_t* glyph = kFont5x7[0];
        unsigned char c = static_cast<unsigned char>(*str++);
        if (c < 0x80) {
            if (c >= 0x20 && c <= 0x5F) glyph = kFont5x7[c - 0x20];
            else if (c >= 'a' && c <= 'z') glyph = kFontLower[c - 'a'];
        } else if (c == 0xD0 && *str) {
            unsigned char d = static_cast<unsigned char>(*str++);
            if (d >= 0x90 && d <= 0xAF) glyph = kFontCyr[d - 0x90];
            else if (d >= 0xB0 && d <= 0xBF) glyph = kFontCyr[d - 0xB0];
            else if (d == 0x81) glyph = kFontCyr[5];
        } else if (c == 0xD1 && *str) {
            unsigned char d = static_cast<unsigned char>(*str++);
            if (d >= 0x80 && d <= 0x8F) glyph = kFontCyr[16 + (d - 0x80)];
            else if (d == 0x91) glyph = kFontCyr[5];
        } else {
            continue;
        }
        LCD_FillRect(x, y, 6 * size, 8 * size, bg);
        for (int col = 0; col < 5; ++col) {
            uint8_t bits = glyph[col];
            for (int row = 0; row < 7; ++row) {
                if (bits & (1 << row)) {
                    LCD_FillRect(x + col * size, y + row * size, size, size, fg);
                }
            }
        }
        x += 6 * size;
    }
}

int LCD_TextWidth(const char* str, int size) {
    int n = 0;
    for (const char* p = str; *p;) {
        unsigned char c = static_cast<unsigned char>(*p++);
        if (c < 0x80) { ++n; }
        else if ((c == 0xD0 || c == 0xD1) && *p) { ++p; ++n; }
    }
    return (n > 0) ? (n * 6 * size - size) : 0;
}

void LCD_TextCentered(int y, const char* str, uint16_t fg, uint16_t bg, int size) {
    int w = LCD_TextWidth(str, size);
    LCD_Text((LCD_W - w) / 2, y, str, fg, bg, size);
}

static const uint8_t kSegMap[10] = {0x3F,0x06,0x5B,0x4F,0x66,0x6D,0x7D,0x07,0x7F,0x6F};

void LCD_SevenSeg(int x, int y, int digit, int L, int T, uint16_t fg, uint16_t bg) {
    if (digit < 0 || digit > 9) digit = 0;
    int w = L + 2 * T;
    int h = 2 * L + 3 * T;
    LCD_FillRect(x, y, w, h, bg);
    uint8_t segs = kSegMap[digit];
    if (segs & 0x01) LCD_FillRect(x + T, y, L, T, fg);
    if (segs & 0x02) LCD_FillRect(x + T + L, y + T, T, L, fg);
    if (segs & 0x04) LCD_FillRect(x + T + L, y + 2 * T + L, T, L, fg);
    if (segs & 0x08) LCD_FillRect(x + T, y + 2 * L + 2 * T, L, T, fg);
    if (segs & 0x10) LCD_FillRect(x, y + 2 * T + L, T, L, fg);
    if (segs & 0x20) LCD_FillRect(x, y + T, T, L, fg);
    if (segs & 0x40) LCD_FillRect(x + T, y + L + T, L, T, fg);
}

void LCD_PushRow(int x, int y, int w, const uint16_t* px) {
    if (w <= 0 || x >= LCD_W || y < 0 || y >= LCD_H) return;
    if (x < 0) { px -= x; w += x; x = 0; }
    if (x + w > LCD_W) w = LCD_W - x;
    if (w <= 0) return;
    LCD_SetWindow(x, y, x + w - 1, y);
    LCD_CS_Low();
    LCD_DC_Data();
    static uint8_t txbuf[256];
    int left = w;
    while (left > 0) {
        int chunk = (left > 128) ? 128 : left;
        for (int i = 0; i < chunk; ++i) {
            txbuf[2 * i] = static_cast<uint8_t>(px[i] >> 8);
            txbuf[2 * i + 1] = static_cast<uint8_t>(px[i] & 0xFF);
        }
        LCD_SpiWrite(txbuf, static_cast<uint32_t>(chunk) * 2);
        px += chunk;
        left -= chunk;
    }
    LCD_CS_High();
}
