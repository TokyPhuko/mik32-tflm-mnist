static constexpr HAL_PinsTypeDef LCD_PIN_CS = GPIO_PIN_5;
static constexpr HAL_PinsTypeDef LCD_PIN_DC = GPIO_PIN_4;
static constexpr HAL_PinsTypeDef LCD_PIN_LED = GPIO_PIN_0;

static constexpr uint8_t SWRESET = 0x01;
static constexpr uint8_t SLPOUT  = 0x11;
static constexpr uint8_t DISPON  = 0x29;
static constexpr uint8_t CASET   = 0x2A;
static constexpr uint8_t PASET   = 0x2B;
static constexpr uint8_t RAMWR   = 0x2C;
static constexpr uint8_t MADCTL  = 0x36;
static constexpr uint8_t COLMOD  = 0x3A;

SPI_HandleTypeDef hspi1;
static uint8_t spi_rx_dummy[256];

extern "C" void HAL_SPI_MspInit(SPI_HandleTypeDef* hspi) {
    if (hspi->Instance != SPI_1) return;
    __HAL_PCC_SPI_1_CLK_ENABLE();
    GPIO_InitTypeDef s = {};
    s.Pin = static_cast<HAL_PinsTypeDef>(GPIO_PIN_1 | GPIO_PIN_2);
    s.Mode = HAL_GPIO_MODE_SERIAL;
    s.Pull = HAL_GPIO_PULL_NONE;
    HAL_GPIO_Init(GPIO_1, &s);
    s.Pin = GPIO_PIN_3;
    s.Mode = HAL_GPIO_MODE_SERIAL;
    s.Pull = HAL_GPIO_PULL_UP;
    HAL_GPIO_Init(GPIO_1, &s);
}

static void LCD_CS_Low()  { HAL_GPIO_WritePin(GPIO_1, LCD_PIN_CS, GPIO_PIN_LOW); }
static void LCD_CS_High() { HAL_GPIO_WritePin(GPIO_1, LCD_PIN_CS, GPIO_PIN_HIGH); }
static void LCD_DC_Cmd()  { HAL_GPIO_WritePin(GPIO_1, LCD_PIN_DC, GPIO_PIN_LOW); }
static void LCD_DC_Data() { HAL_GPIO_WritePin(GPIO_1, LCD_PIN_DC, GPIO_PIN_HIGH); }

static void LCD_SpiWrite(const uint8_t* data, uint32_t len) {
    while (len > 0) {
        uint32_t chunk = (len > sizeof(spi_rx_dummy)) ? sizeof(spi_rx_dummy) : len;
        HAL_SPI_Exchange(&hspi1, const_cast<uint8_t*>(data), spi_rx_dummy, chunk, SPI_TIMEOUT_DEFAULT);
        data += chunk;
        len -= chunk;
    }
}

static void LCD_WriteCmd(uint8_t cmd) {
    LCD_CS_Low();
    LCD_DC_Cmd();
    LCD_SpiWrite(&cmd, 1);
    LCD_DC_Data();
}

static void LCD_WriteData(const uint8_t* data, uint32_t len) {
    LCD_SpiWrite(data, len);
    LCD_CS_High();
}

static void LCD_WriteCmdData(uint8_t cmd, const uint8_t* data, uint32_t len) {
    LCD_WriteCmd(cmd);
    LCD_WriteData(data, len);
}

void LCD_Init(void) {
    __HAL_PCC_GPIO_1_CLK_ENABLE();
    GPIO_InitTypeDef s = {};
    s.Pin = static_cast<HAL_PinsTypeDef>(GPIO_PIN_4 | GPIO_PIN_5 | GPIO_PIN_0);
    s.Mode = HAL_GPIO_MODE_GPIO_OUTPUT;
    s.Pull = HAL_GPIO_PULL_NONE;
    HAL_GPIO_Init(GPIO_1, &s);
    HAL_GPIO_WritePin(GPIO_1, LCD_PIN_CS, GPIO_PIN_HIGH);
    hspi1.Instance = SPI_1;
    hspi1.Init.SPI_Mode = HAL_SPI_MODE_MASTER;
    hspi1.Init.CLKPhase = SPI_PHASE_OFF;
    hspi1.Init.CLKPolarity = SPI_POLARITY_LOW;
    hspi1.Init.ThresholdTX = 4;
    hspi1.Init.BaudRateDiv = SPI_BAUDRATE_DIV4;
    hspi1.Init.Decoder = SPI_DECODER_NONE;
    hspi1.Init.ManualCS = SPI_MANUALCS_ON;
    hspi1.Init.ChipSelect = SPI_CS_0;
    HAL_SPI_Init(&hspi1);
    __HAL_SPI_ENABLE(&hspi1);
    LCD_WriteCmd(SWRESET); HAL_DelayMs(150);
    LCD_WriteCmd(SLPOUT);  HAL_DelayMs(150);
    static const uint8_t cfg_CF[] = {0x00, 0xC1, 0x30};
    LCD_WriteCmdData(0xCF, cfg_CF, 3);
    static const uint8_t cfg_ED[] = {0x64, 0x03, 0x12, 0x81};
    LCD_WriteCmdData(0xED, cfg_ED, 4);
    static const uint8_t cfg_E8[] = {0x85, 0x00, 0x78};
    LCD_WriteCmdData(0xE8, cfg_E8, 3);
    static const uint8_t cfg_CB[] = {0x39, 0x2C, 0x00, 0x34, 0x02};
    LCD_WriteCmdData(0xCB, cfg_CB, 5);
    static const uint8_t cfg_F7 = 0x20;
    LCD_WriteCmdData(0xF7, &cfg_F7, 1);
    static const uint8_t cfg_EA[] = {0x00, 0x00};
    LCD_WriteCmdData(0xEA, cfg_EA, 2);
    static const uint8_t cfg_C0 = 0x23;
    LCD_WriteCmdData(0xC0, &cfg_C0, 1);
    static const uint8_t cfg_C1 = 0x10;
    LCD_WriteCmdData(0xC1, &cfg_C1, 1);
    static const uint8_t cfg_C5[] = {0x3E, 0x28};
    LCD_WriteCmdData(0xC5, cfg_C5, 2);
    static const uint8_t cfg_C7 = 0x86;
    LCD_WriteCmdData(0xC7, &cfg_C7, 1);
    static const uint8_t madctl = 0x68;
    LCD_WriteCmdData(MADCTL, &madctl, 1);
    static const uint8_t cfg_COL = 0x55;
    LCD_WriteCmdData(COLMOD, &cfg_COL, 1);
    static const uint8_t cfg_B1[] = {0x00, 0x18};
    LCD_WriteCmdData(0xB1, cfg_B1, 2);
    static const uint8_t cfg_B6[] = {0x08, 0x82, 0x27};
    LCD_WriteCmdData(0xB6, cfg_B6, 3);
    static const uint8_t cfg_F2 = 0x00;
    LCD_WriteCmdData(0xF2, &cfg_F2, 1);
    static const uint8_t cfg_GAM = 0x01;
    LCD_WriteCmdData(0x26, &cfg_GAM, 1);
    static const uint8_t cfg_E0[] = {0x0F, 0x31, 0x2B, 0x0C, 0x0E, 0x08, 0x4E, 0xF1, 0x37, 0x07, 0x10, 0x03, 0x0E, 0x09, 0x00};
    LCD_WriteCmdData(0xE0, cfg_E0, 15);
    static const uint8_t cfg_E1[] = {0x00, 0x0E, 0x14, 0x03, 0x11, 0x07, 0x31, 0xC1, 0x48, 0x08, 0x0F, 0x0C, 0x31, 0x36, 0x0F};
    LCD_WriteCmdData(0xE1, cfg_E1, 15);
    LCD_WriteCmd(DISPON); HAL_DelayMs(100);
    HAL_GPIO_WritePin(GPIO_1, LCD_PIN_LED, GPIO_PIN_HIGH);
    LCD_FillScreen(POLY_BG);
}

static void LCD_SetWindow(int x0, int y0, int x1, int y1) {
    uint8_t buf[4];
    buf[0] = static_cast<uint8_t>(x0 >> 8); buf[1] = static_cast<uint8_t>(x0 & 0xFF);
    buf[2] = static_cast<uint8_t>(x1 >> 8); buf[3] = static_cast<uint8_t>(x1 & 0xFF);
    LCD_WriteCmdData(CASET, buf, 4);
    buf[0] = static_cast<uint8_t>(y0 >> 8); buf[1] = static_cast<uint8_t>(y0 & 0xFF);
    buf[2] = static_cast<uint8_t>(y1 >> 8); buf[3] = static_cast<uint8_t>(y1 & 0xFF);
    LCD_WriteCmdData(PASET, buf, 4);
    LCD_WriteCmd(RAMWR);
}

static bool LCD_Clip(int* x, int* y, int* w, int* h) {
    if (*w <= 0 || *h <= 0) return false;
    if (*x < 0) { *w += *x; *x = 0; }
    if (*y < 0) { *h += *y; *y = 0; }
    if (*x + *w > LCD_W) *w = LCD_W - *x;
    if (*y + *h > LCD_H) *h = LCD_H - *y;
    return (*w > 0 && *h > 0);
}

void LCD_FillRect(int x, int y, int w, int h, uint16_t color) {
    if (!LCD_Clip(&x, &y, &w, &h)) return;
    LCD_SetWindow(x, y, x + w - 1, y + h - 1);
    static uint8_t txbuf[256];
    for (int i = 0; i < 128; ++i) {
        txbuf[2 * i] = static_cast<uint8_t>(color >> 8);
        txbuf[2 * i + 1] = static_cast<uint8_t>(color & 0xFF);
    }
    LCD_CS_Low();
    LCD_DC_Data();
    uint32_t left = static_cast<uint32_t>(w) * static_cast<uint32_t>(h) * 2;
    while (left > 0) {
        uint32_t chunk = (left > sizeof(txbuf)) ? sizeof(txbuf) : left;
        LCD_SpiWrite(txbuf, chunk);
        left -= chunk;
    }
    LCD_CS_High();
}

void LCD_FillScreen(uint16_t color) { LCD_FillRect(0, 0, LCD_W, LCD_H, color); }

void LCD_DrawPixel(int x, int y, uint16_t color) {
    if (x < 0 || x >= LCD_W || y < 0 || y >= LCD_H) return;
    LCD_SetWindow(x, y, x, y);
    uint8_t px[2] = {static_cast<uint8_t>(color >> 8), static_cast<uint8_t>(color & 0xFF)};
    LCD_CS_Low();
    LCD_DC_Data();
    LCD_SpiWrite(px, 2);
    LCD_CS_High();
}

void LCD_DrawCircle(int cx, int cy, int r, uint16_t color) {
    int x = r, y = 0, err = 0;
    while (x >= y) {
        LCD_DrawPixel(cx + x, cy + y, color);
        LCD_DrawPixel(cx + y, cy + x, color);
        LCD_DrawPixel(cx - y, cy + x, color);
        LCD_DrawPixel(cx - x, cy + y, color);
        LCD_DrawPixel(cx - x, cy - y, color);
        LCD_DrawPixel(cx - y, cy - x, color);
        LCD_DrawPixel(cx + y, cy - x, color);
        LCD_DrawPixel(cx + x, cy - y, color);
        ++y;
        err += 1 + 2 * y;
        if (2 * (err - x) + 1 > 0) { --x; err += 1 - 2 * x; }
    }
}

